import React, { useState, useMemo } from 'react';
import {
  Bookmark,
  BookOpen,
  Trash2,
  ExternalLink,
  Search,
  CheckCircle2,
  Clock,
  Sparkles,
  MessageSquare,
  Copy,
  Check,
  Plus,
  Atom,
  Layers,
  ChevronRight,
  HelpCircle,
  FileText,
  Edit3,
} from 'lucide-react';
import { Topic, Character } from '../types';

interface ReadingListPanelProps {
  savedTopicIds: string[];
  topics: Topic[];
  activeTopic: Topic;
  onSelectTopic: (topic: Topic) => void;
  onToggleSaveTopic: (topicId: string) => void;
  onAskTutorAboutTopic: (topic: Topic, initialQuery?: string) => void;
  character: Character;
  darkMode: boolean;
  onAwardXp: (amount: number, reason: string) => void;
}

export const ReadingListPanel: React.FC<ReadingListPanelProps> = ({
  savedTopicIds,
  topics,
  activeTopic,
  onSelectTopic,
  onToggleSaveTopic,
  onAskTutorAboutTopic,
  character,
  darkMode,
  onAwardXp,
}) => {
  const [searchQuery, setSearchQuery] = useState<string>('');
  const [selectedCategory, setSelectedCategory] = useState<string>('all');
  const [copiedChecklist, setCopiedChecklist] = useState<boolean>(false);
  const [activeNoteTopicId, setActiveNoteTopicId] = useState<string | null>(null);

  // Per-topic user study notes stored in localStorage
  const [topicNotes, setTopicNotes] = useState<Record<string, string>>(() => {
    if (typeof window !== 'undefined') {
      try {
        const saved = localStorage.getItem('biofocus_saved_notes');
        if (saved) return JSON.parse(saved);
      } catch {
        // fallback
      }
    }
    return {};
  });

  const handleSaveNote = (topicId: string, note: string) => {
    const updated = { ...topicNotes, [topicId]: note };
    setTopicNotes(updated);
    if (typeof window !== 'undefined') {
      localStorage.setItem('biofocus_saved_notes', JSON.stringify(updated));
    }
  };

  // Resolve saved topics from full topic catalogue
  const savedTopics = useMemo(() => {
    return savedTopicIds
      .map((id) => topics.find((t) => t.id === id))
      .filter((t): t is Topic => Boolean(t));
  }, [savedTopicIds, topics]);

  // Filter saved topics based on search query and category
  const filteredSavedTopics = useMemo(() => {
    return savedTopics.filter((t) => {
      const matchesSearch =
        searchQuery.trim() === '' ||
        t.title.toLowerCase().includes(searchQuery.toLowerCase()) ||
        t.subtitle.toLowerCase().includes(searchQuery.toLowerCase()) ||
        t.category.toLowerCase().includes(searchQuery.toLowerCase());

      const matchesCat =
        selectedCategory === 'all' ||
        (selectedCategory === 'cells' &&
          (t.structureType === 'cell_organelle' ||
            t.structureType === 'neuron' ||
            t.structureType === 'mitochondria' ||
            t.structureType === 'tissue')) ||
        (selectedCategory === 'molecules' &&
          (t.structureType === 'small_molecule' ||
            t.structureType === 'protein' ||
            t.chemicalFormula)) ||
        (selectedCategory === 'genetics' &&
          (t.structureType === 'dna_helix' || t.category.toLowerCase().includes('genetic')));

      return matchesSearch && matchesCat;
    });
  }, [savedTopics, searchQuery, selectedCategory]);

  // Calculate total reading minutes
  const totalReadMinutes = useMemo(() => {
    return savedTopics.reduce((acc, t) => {
      const match = t.readTime?.match(/\d+/);
      const mins = match ? parseInt(match[0], 10) : 4;
      return acc + mins;
    }, 0);
  }, [savedTopics]);

  const isActiveTopicSaved = savedTopicIds.includes(activeTopic.id);

  // Recommendations when list is empty
  const recommendedTopics = useMemo(() => {
    const popularIds = ['cellular-structure', 'neuron-cell', 'mitochondria-organelle', 'dna-double-helix'];
    return popularIds
      .map((id) => topics.find((t) => t.id === id))
      .filter((t): t is Topic => t !== undefined && !savedTopicIds.includes(t.id));
  }, [topics, savedTopicIds]);

  const handleCopyChecklist = () => {
    if (savedTopics.length === 0) return;
    const checklistText = [
      `# 📋 My BioFocus Study Reading List`,
      `Estimated Total Study Time: ~${totalReadMinutes} minutes`,
      '',
      ...savedTopics.map((t, idx) => {
        const note = topicNotes[t.id];
        return `- [ ] **${idx + 1}. ${t.title.split(':')[0]}** (${t.readTime}) - *${t.category}*${
          note ? `\n      Note: ${note}` : ''
        }`;
      }),
      '',
      `Generated by BioFocus Learning Studio`,
    ].join('\n');

    navigator.clipboard.writeText(checklistText);
    setCopiedChecklist(true);
    onAwardXp(10, 'Exported Personal Study Reading Checklist');
    setTimeout(() => setCopiedChecklist(false), 2500);
  };

  const getTopicIcon = (t: Topic) => {
    if (t.id === 'cellular-structure' || t.structureType === 'cell_organelle') return '🔬';
    if (t.id === 'neuron-cell' || t.structureType === 'neuron') return '🧠';
    if (t.id === 'mitochondria-organelle' || t.structureType === 'mitochondria') return '⚡';
    if (t.id === 'dna-double-helix' || t.structureType === 'dna_helix') return '🧬';
    if (t.id === 'sugar-glucose') return '🍬';
    if (t.id === 'methane-molecule') return '📐';
    if (t.id === 'gfp-jellyfish') return '💡';
    if (t.id === 'hemoglobin-submarine') return '🩸';
    if (t.id === 'insulin-key') return '🔑';
    if (t.id === 'antibody-guardian') return '🛡️';
    return '🧪';
  };

  return (
    <div className="space-y-4 select-none animate-in fade-in duration-200">
      {/* 1. Header Overview & Stats Card */}
      <div className="p-4 rounded-2xl bg-gradient-to-tr from-amber-500/10 via-amber-500/5 to-transparent border border-amber-200/60 dark:border-amber-800/40 space-y-3">
        <div className="flex items-center justify-between gap-2">
          <div className="flex items-center gap-2">
            <div className="w-8 h-8 rounded-xl bg-amber-500 text-white flex items-center justify-center shadow-md shadow-amber-500/20">
              <Bookmark className="w-4 h-4 fill-white" />
            </div>
            <div>
              <h3 className="text-sm font-bold text-slate-900 dark:text-white">
                Personal Reading List
              </h3>
              <p className="text-[11px] text-slate-500 dark:text-slate-400">
                Topics bookmarked for later revision and Socratic review
              </p>
            </div>
          </div>

          {savedTopics.length > 0 && (
            <button
              type="button"
              onClick={handleCopyChecklist}
              className="px-2.5 py-1 rounded-lg bg-white dark:bg-slate-800 hover:bg-slate-100 dark:hover:bg-slate-700 text-slate-700 dark:text-slate-300 border border-slate-200 dark:border-slate-700 text-[11px] font-semibold flex items-center gap-1.5 transition-colors shadow-2xs cursor-pointer"
              title="Copy formatted study checklist to clipboard"
            >
              {copiedChecklist ? (
                <>
                  <Check className="w-3.5 h-3.5 text-emerald-500" />
                  <span className="text-emerald-600 dark:text-emerald-400">Copied!</span>
                </>
              ) : (
                <>
                  <Copy className="w-3.5 h-3.5 text-slate-400" />
                  <span>Copy Checklist</span>
                </>
              )}
            </button>
          )}
        </div>

        {/* Quick Stats Badges */}
        <div className="flex flex-wrap items-center gap-2 pt-1 text-xs">
          <span className="px-2.5 py-1 rounded-lg bg-white dark:bg-slate-800 border border-slate-200 dark:border-slate-700/80 text-slate-700 dark:text-slate-300 font-medium flex items-center gap-1.5 shadow-2xs">
            <BookOpen className="w-3.5 h-3.5 text-amber-500" />
            <span>
              <strong>{savedTopics.length}</strong> {savedTopics.length === 1 ? 'Topic' : 'Topics'} Saved
            </span>
          </span>

          <span className="px-2.5 py-1 rounded-lg bg-white dark:bg-slate-800 border border-slate-200 dark:border-slate-700/80 text-slate-700 dark:text-slate-300 font-medium flex items-center gap-1.5 shadow-2xs">
            <Clock className="w-3.5 h-3.5 text-amber-500" />
            <span>
              ~<strong>{totalReadMinutes}</strong> min Total Reading
            </span>
          </span>
        </div>

        {/* 1-Click Save / Remove Current Topic Button */}
        <div className="pt-2 border-t border-amber-200/40 dark:border-amber-800/30 flex items-center justify-between gap-2">
          <div className="flex items-center gap-1.5 min-w-0">
            <span className="text-xs text-slate-500 dark:text-slate-400 shrink-0">Currently Viewing:</span>
            <span className="text-xs font-semibold text-slate-800 dark:text-slate-200 truncate">
              {activeTopic.title.split(':')[0]}
            </span>
          </div>

          <button
            type="button"
            onClick={() => onToggleSaveTopic(activeTopic.id)}
            className={`px-3 py-1 rounded-xl text-xs font-semibold shrink-0 transition-all flex items-center gap-1.5 cursor-pointer ${
              isActiveTopicSaved
                ? 'bg-amber-100 dark:bg-amber-950/80 text-amber-800 dark:text-amber-300 border border-amber-300 dark:border-amber-700'
                : 'bg-amber-500 hover:bg-amber-600 text-white shadow-xs'
            }`}
          >
            <Bookmark className={`w-3.5 h-3.5 ${isActiveTopicSaved ? 'fill-amber-600' : 'fill-white'}`} />
            <span>{isActiveTopicSaved ? 'Saved in List' : 'Save for Later'}</span>
          </button>
        </div>
      </div>

      {/* 2. Search & Category Filters (When topics exist) */}
      {savedTopics.length > 0 && (
        <div className="space-y-2">
          {/* Search Bar */}
          <div className="relative">
            <div className="absolute inset-y-0 left-0 pl-3 flex items-center pointer-events-none text-slate-400">
              <Search className="w-3.5 h-3.5" />
            </div>
            <input
              type="text"
              value={searchQuery}
              onChange={(e) => setSearchQuery(e.target.value)}
              placeholder="Search your saved reading list..."
              className="w-full pl-9 pr-3 py-1.5 text-xs rounded-xl bg-slate-100 dark:bg-slate-800 border border-slate-200 dark:border-slate-700 text-slate-900 dark:text-white placeholder:text-slate-400 focus:outline-hidden focus:ring-1 focus:ring-amber-500"
            />
          </div>

          {/* Category Filter Pills */}
          <div className="flex flex-wrap items-center gap-1 text-[11px]">
            {[
              { id: 'all', label: 'All Saved' },
              { id: 'cells', label: 'Cells & Organelles' },
              { id: 'molecules', label: 'Molecules' },
              { id: 'genetics', label: 'Genetics' },
            ].map((cat) => (
              <button
                key={cat.id}
                type="button"
                onClick={() => setSelectedCategory(cat.id)}
                className={`px-2.5 py-0.5 rounded-lg font-medium transition-colors cursor-pointer ${
                  selectedCategory === cat.id
                    ? 'bg-amber-500 text-white shadow-2xs'
                    : 'bg-slate-100 dark:bg-slate-800 text-slate-600 dark:text-slate-400 hover:text-slate-900 dark:hover:text-white'
                }`}
              >
                {cat.label}
              </button>
            ))}
          </div>
        </div>
      )}

      {/* 3. List of Saved Topics */}
      {filteredSavedTopics.length > 0 ? (
        <div className="space-y-2.5">
          {filteredSavedTopics.map((item) => {
            const isCurrentlyActive = item.id === activeTopic.id;
            const note = topicNotes[item.id] || '';
            const isEditingNote = activeNoteTopicId === item.id;

            return (
              <div
                key={item.id}
                className={`p-3.5 rounded-2xl border transition-all text-left space-y-2 ${
                  isCurrentlyActive
                    ? 'bg-amber-50/60 dark:bg-amber-950/30 border-amber-300 dark:border-amber-800/80 shadow-xs ring-1 ring-amber-400/40'
                    : 'bg-white dark:bg-slate-800/70 border-slate-200 dark:border-slate-800 hover:border-amber-300 dark:hover:border-amber-700/60 shadow-2xs'
                }`}
              >
                {/* Top Row: Icon, Category & Remove Action */}
                <div className="flex items-start justify-between gap-2">
                  <div className="flex items-center gap-2">
                    <span className="text-xl shrink-0" aria-hidden="true">
                      {getTopicIcon(item)}
                    </span>
                    <div>
                      <div className="flex items-center gap-2">
                        <span className="px-2 py-0.5 rounded-md bg-amber-100/80 dark:bg-amber-950/80 text-amber-800 dark:text-amber-300 text-[10px] font-semibold">
                          {item.category}
                        </span>
                        <span className="text-[10px] text-slate-400">{item.difficulty}</span>
                      </div>
                      <h4 className="text-xs sm:text-sm font-bold text-slate-900 dark:text-white mt-0.5">
                        {item.title}
                      </h4>
                    </div>
                  </div>

                  {/* Remove Button */}
                  <button
                    type="button"
                    onClick={() => onToggleSaveTopic(item.id)}
                    className="p-1 rounded-lg text-slate-400 hover:text-rose-600 hover:bg-rose-50 dark:hover:bg-rose-950/50 transition-colors cursor-pointer"
                    title="Remove from reading list"
                  >
                    <Trash2 className="w-3.5 h-3.5" />
                  </button>
                </div>

                {/* Subtitle / Key Takeaway */}
                <p className="text-[11px] text-slate-600 dark:text-slate-300 leading-relaxed line-clamp-2">
                  {item.subtitle || item.summary}
                </p>

                {/* Study Note Preview / Input */}
                {isEditingNote ? (
                  <div className="pt-1 space-y-1.5 animate-in fade-in duration-150">
                    <input
                      type="text"
                      defaultValue={note}
                      placeholder="Add a quick revision goal or key question..."
                      autoFocus
                      onBlur={(e) => {
                        handleSaveNote(item.id, e.target.value.trim());
                        setActiveNoteTopicId(null);
                      }}
                      onKeyDown={(e) => {
                        if (e.key === 'Enter') {
                          handleSaveNote(item.id, (e.target as HTMLInputElement).value.trim());
                          setActiveNoteTopicId(null);
                        }
                      }}
                      className="w-full px-2.5 py-1 text-[11px] rounded-lg bg-amber-50/50 dark:bg-amber-950/30 border border-amber-300 dark:border-amber-700 text-slate-800 dark:text-slate-200 focus:outline-hidden"
                    />
                    <div className="flex items-center justify-between text-[10px] text-slate-400">
                      <span>Press Enter or click away to save note</span>
                      <button
                        type="button"
                        onClick={() => setActiveNoteTopicId(null)}
                        className="text-amber-600 hover:underline"
                      >
                        Cancel
                      </button>
                    </div>
                  </div>
                ) : note ? (
                  <div
                    onClick={() => setActiveNoteTopicId(item.id)}
                    className="p-2 rounded-lg bg-amber-50/70 dark:bg-amber-950/40 border border-amber-200/70 dark:border-amber-900/40 text-[11px] text-amber-900 dark:text-amber-200 flex items-start justify-between gap-2 cursor-pointer hover:border-amber-300"
                    title="Click to edit study note"
                  >
                    <div className="flex items-center gap-1.5">
                      <FileText className="w-3.5 h-3.5 text-amber-600 shrink-0" />
                      <span>{note}</span>
                    </div>
                    <Edit3 className="w-3 h-3 text-amber-500 shrink-0 opacity-60" />
                  </div>
                ) : (
                  <button
                    type="button"
                    onClick={() => setActiveNoteTopicId(item.id)}
                    className="text-[10px] text-slate-400 hover:text-amber-600 dark:hover:text-amber-400 flex items-center gap-1 transition-colors cursor-pointer"
                  >
                    <Plus className="w-3 h-3" />
                    <span>Add revision note</span>
                  </button>
                )}

                {/* Bottom Action Deck */}
                <div className="pt-2 border-t border-slate-100 dark:border-slate-700/60 flex items-center justify-between gap-2">
                  <div className="flex items-center gap-2 text-[10px] text-slate-400">
                    <Clock className="w-3 h-3" />
                    <span>{item.readTime}</span>
                    {item.structureType && (
                      <>
                        <span>•</span>
                        <span className="font-mono text-indigo-500 dark:text-indigo-400">
                          {item.structureType === 'cell_organelle'
                            ? '3D Cell Mesh'
                            : item.structureType === 'neuron'
                            ? '3D Nerve Model'
                            : item.structureType === 'mitochondria'
                            ? '3D Organelle'
                            : '3D Molecular'}
                        </span>
                      </>
                    )}
                  </div>

                  <div className="flex items-center gap-1.5">
                    <button
                      type="button"
                      onClick={() =>
                        onAskTutorAboutTopic(item, `What are the core concepts I should review about ${item.title.split(':')[0]}?`)
                      }
                      className="px-2.5 py-1 rounded-lg bg-slate-100 hover:bg-indigo-50 dark:bg-slate-700 dark:hover:bg-indigo-950/50 text-slate-700 dark:text-slate-300 hover:text-indigo-600 text-[11px] font-semibold flex items-center gap-1 transition-colors cursor-pointer"
                      title={`Ask ${character.name} for revision guidance`}
                    >
                      <MessageSquare className="w-3 h-3" />
                      <span className="hidden sm:inline">Ask {character.name.split(' ')[0]}</span>
                    </button>

                    <button
                      type="button"
                      onClick={() => onSelectTopic(item)}
                      className="px-3 py-1 rounded-lg bg-indigo-600 hover:bg-indigo-700 text-white text-[11px] font-semibold flex items-center gap-1 transition-colors shadow-2xs cursor-pointer"
                    >
                      <span>Study Now</span>
                      <ChevronRight className="w-3 h-3" />
                    </button>
                  </div>
                </div>
              </div>
            );
          })}
        </div>
      ) : savedTopics.length > 0 ? (
        // Search returned no matches within saved topics
        <div className="p-6 text-center space-y-2 rounded-2xl border border-dashed border-slate-200 dark:border-slate-800">
          <Search className="w-8 h-8 text-slate-300 dark:text-slate-600 mx-auto" />
          <p className="text-xs font-semibold text-slate-700 dark:text-slate-300">
            No saved topics match &quot;{searchQuery}&quot;
          </p>
          <button
            type="button"
            onClick={() => {
              setSearchQuery('');
              setSelectedCategory('all');
            }}
            className="text-[11px] text-amber-600 dark:text-amber-400 font-semibold underline"
          >
            Clear filters
          </button>
        </div>
      ) : (
        // Completely Empty State with Curated Recommendations
        <div className="space-y-4">
          <div className="p-6 rounded-2xl border border-dashed border-amber-300/80 dark:border-amber-800/60 bg-amber-50/40 dark:bg-amber-950/20 text-center space-y-2.5">
            <div className="w-12 h-12 rounded-2xl bg-amber-100 dark:bg-amber-950/80 text-amber-600 dark:text-amber-400 flex items-center justify-center mx-auto shadow-xs">
              <Bookmark className="w-6 h-6" />
            </div>
            <h4 className="text-xs sm:text-sm font-bold text-slate-900 dark:text-white">
              Your Reading List is Empty
            </h4>
            <p className="text-[11px] text-slate-600 dark:text-slate-400 max-w-sm mx-auto leading-relaxed">
              Bookmark intriguing cellular structures, organelles, and biomolecules while exploring to create your personalized revision checklist!
            </p>

            <button
              type="button"
              onClick={() => onToggleSaveTopic(activeTopic.id)}
              className="mt-2 px-3.5 py-1.5 rounded-xl bg-amber-500 hover:bg-amber-600 text-white text-xs font-semibold inline-flex items-center gap-1.5 shadow-xs transition-colors cursor-pointer"
            >
              <Bookmark className="w-3.5 h-3.5 fill-white" />
              <span>Save Current: {activeTopic.title.split(':')[0]}</span>
            </button>
          </div>

          {/* Curated Recommendations to Start */}
          {recommendedTopics.length > 0 && (
            <div className="space-y-2">
              <div className="flex items-center gap-1.5 text-xs font-bold text-slate-800 dark:text-slate-200">
                <Sparkles className="w-3.5 h-3.5 text-amber-500" />
                <span>Recommended Topics to Bookmark:</span>
              </div>

              <div className="grid grid-cols-1 gap-2">
                {recommendedTopics.slice(0, 3).map((rec) => (
                  <div
                    key={rec.id}
                    className="p-3 rounded-xl bg-white dark:bg-slate-800/80 border border-slate-200 dark:border-slate-700/80 flex items-center justify-between gap-3 text-left hover:border-amber-300 transition-colors shadow-2xs"
                  >
                    <div className="flex items-center gap-2 min-w-0">
                      <span className="text-lg shrink-0">{getTopicIcon(rec)}</span>
                      <div className="truncate">
                        <div className="text-xs font-bold text-slate-900 dark:text-white truncate">
                          {rec.title.split(':')[0]}
                        </div>
                        <div className="text-[10px] text-slate-500 dark:text-slate-400">
                          {rec.category} · {rec.readTime}
                        </div>
                      </div>
                    </div>

                    <button
                      type="button"
                      onClick={() => onToggleSaveTopic(rec.id)}
                      className="px-2.5 py-1 rounded-lg bg-amber-50 hover:bg-amber-100 dark:bg-amber-950/60 dark:hover:bg-amber-900/60 text-amber-700 dark:text-amber-300 border border-amber-200 dark:border-amber-800 text-[11px] font-semibold shrink-0 flex items-center gap-1 transition-colors cursor-pointer"
                      title="Add to Reading List"
                    >
                      <Plus className="w-3 h-3" />
                      <span>Bookmark</span>
                    </button>
                  </div>
                ))}
              </div>
            </div>
          )}
        </div>
      )}
    </div>
  );
};
